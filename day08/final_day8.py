import pandas as pd

data = {
    "Имя": ["Варвара", "Сергей", "Надежда", "Константин", "Иван", "Наталья", "Антон", "Ксения"],
    "Группа": ["1ИИ-1", "2ИИ-1", "2ИИ-1", "1ИИ-2", "1ИИ-1", "1ИИ-2", "2ИИ-1", "1ИИ-1"],
    "Баллы": [98, 34, 56, 67, 42, 88, 70, 51],
    "Посещено занятий": [8, 6, 5, 6, 10, 8, 6, 4]
}

df = pd.DataFrame(data)

df["Всего занятий"] = 10
df["Процент посещаемости"] = df["Посещено занятий"] / df["Всего занятий"] * 100

average = df["Баллы"].mean()
result = df[df["Баллы"] > average]

st = pd.DataFrame(result)
print(st)